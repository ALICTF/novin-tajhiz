#!/bin/sh
set -eu

# ---------------------------------------------------------------------------
# حلقه زمان‌بندی پشتیبان‌گیری.
#
# عمداً از cron استفاده نشده: cron داخل کانتینر آلپاین متغیرهای محیطی را به
# اسکریپت نمی‌رساند مگر با ترفند، و لاگش هم به stdout کانتینر نمی‌رود. یک
# حلقه ساده هر دو مشکل را ندارد و رفتارش قابل پیش‌بینی است.
#
# BACKUP_INTERVAL_HOURS فاصله بین دو اجراست (پیش‌فرض ۲۴ ساعت).
# ---------------------------------------------------------------------------

INTERVAL_HOURS="${BACKUP_INTERVAL_HOURS:-24}"
INTERVAL_SECONDS=$((INTERVAL_HOURS * 3600))

echo "[backup] سرویس پشتیبان‌گیری آماده است — هر $INTERVAL_HOURS ساعت"

# کمی صبر تا دیتابیس کاملاً بالا بیاید.
sleep 15

while true; do
  # شکست یک نوبت نباید سرویس را بکشد؛ نوبت بعدی دوباره تلاش می‌کند.
  /backup.sh || echo "[backup] این نوبت ناموفق بود؛ نوبت بعدی دوباره تلاش می‌شود"
  sleep "$INTERVAL_SECONDS"
done
